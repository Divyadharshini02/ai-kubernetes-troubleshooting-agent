"""The AI root cause analysis of a whole investigation, kept apart from the deterministic report."""

from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from app.models.explanation import ExplanationReason

Text = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=600)]
ShortText = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=400)]
Command = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=300)]
EvidenceId = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=300)]
EvidenceIds = Annotated[list[EvidenceId], Field(min_length=1, max_length=8)]
# The documented evidence-strength levels. Never a percentage.
Confidence = Literal["high", "medium", "low", "insufficient"]
CONFIDENCE_ORDER = ("insufficient", "low", "medium", "high")


class _Strict(BaseModel):
    """Model output: any field that is missing, extra or of the wrong type causes rejection."""

    model_config = ConfigDict(extra="forbid", strict=True)


class RootCause(_Strict):
    statement: Text
    # confirmed: directly shown by the cited evidence. hypothesis: an inference that may be wrong.
    kind: Literal["confirmed", "hypothesis"]
    evidence_ids: EvidenceIds


class SupportingEvidence(_Strict):
    evidence_id: EvidenceId
    observation: ShortText


class AlternativeCause(_Strict):
    statement: ShortText
    evidence_ids: EvidenceIds


class RemediationStep(_Strict):
    """Advice for a person. The application never runs these commands."""

    action: ShortText
    why: ShortText
    risk: Literal["low", "medium", "high"]
    commands: Annotated[list[Command], Field(max_length=4)]
    evidence_ids: EvidenceIds


class RcaContent(_Strict):
    """The only shape accepted from the model."""

    summary: Text
    root_cause: RootCause
    reasoning: Annotated[list[ShortText], Field(min_length=1, max_length=6)]
    supporting_evidence: Annotated[list[SupportingEvidence], Field(min_length=1, max_length=8)]
    confidence: Confidence
    limitations: Annotated[list[ShortText], Field(max_length=6)]
    alternative_causes: Annotated[list[AlternativeCause], Field(max_length=4)]
    remediation: Annotated[list[RemediationStep], Field(max_length=5)]
    verification_steps: Annotated[list[ShortText], Field(max_length=5)]


class AiAnalysis(BaseModel):
    """One analysis per investigation. Generated content is labelled, and checked before it is kept."""

    status: Literal["generated", "unavailable", "not_needed"]
    provider: str
    model: str | None = None
    reason: ExplanationReason | None = None
    message: str | None = None
    notice: str = (
        "Generated by an LLM from the evidence below. It may contain mistakes. Commands are suggestions "
        "for a person to review and run: the application never runs them."
    )
    content: RcaContent | None = None
    # The model's own confidence, before the application limited it to what the evidence supports.
    model_confidence: Confidence | None = None
    confidence_limited: bool = False
    # Exactly what the model was shown, so every citation can be followed.
    evidence_ids_sent: list[str] = []
    evidence_omitted: int = 0
