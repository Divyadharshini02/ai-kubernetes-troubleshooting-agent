from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

ShortText = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=400)]

ExplanationReason = Literal[
    "disabled",
    "missing_api_key",
    "missing_model",
    "invalid_configuration",
    "timeout",
    "network_error",
    "unauthorized",
    "insufficient_credits",
    "provider_refused",
    "model_not_found",
    "bad_request",
    "rate_limited",
    "provider_error",
    "empty_response",
    "response_truncated",
    "response_too_large",
    "malformed_response",
    "schema_validation_failed",
    "unsupported_claim",
    "limit_reached",
    "time_budget_exhausted",
    "unexpected_error",
]


class LlmExplanationContent(BaseModel):
    """The only shape accepted from the model. Any other field causes rejection."""

    model_config = ConfigDict(extra="forbid", strict=True)

    explanation: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=1500)]
    impact: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=800)]
    evidence_summary: Annotated[list[ShortText], Field(min_length=1, max_length=8)]
    investigation_steps: Annotated[list[ShortText], Field(max_length=8)]
    limitations: Annotated[list[ShortText], Field(max_length=6)]


class DiagnosisExplanation(BaseModel):
    # Taken from the deterministic diagnosis, never from the model.
    diagnosis_id: str
    source_evidence_ids: list[str]
    status: Literal["generated", "unavailable"]
    reason: ExplanationReason | None = None
    message: str | None = None
    content: LlmExplanationContent | None = None


class LlmReport(BaseModel):
    """Generated text, kept apart from the deterministic diagnoses it describes."""

    used: bool
    status: Literal["generated", "partial", "unavailable", "not_needed"]
    provider: str
    model: str | None = None
    reason: ExplanationReason | None = None
    message: str | None = None
    notice: str = (
        "Generated by an LLM from the deterministic diagnosis. It may contain mistakes. "
        "The deterministic diagnoses are authoritative, and nothing here was executed."
    )
    explanations: list[DiagnosisExplanation] = []
