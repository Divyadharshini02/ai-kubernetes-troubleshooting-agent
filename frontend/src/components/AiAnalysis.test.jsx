import { cleanup, render, screen, within } from '@testing-library/react'
import { afterEach, describe, expect, it } from 'vitest'
import { analysis, EVIDENCE_ID } from '../test/fixtures.js'
import AiAnalysis from './AiAnalysis.jsx'

afterEach(cleanup)

function panel() {
  return screen.getByRole('region', { name: 'AI root cause analysis' })
}

describe('AiAnalysis', () => {
  it('shows a generated analysis, labelled as generated by an LLM', () => {
    render(<AiAnalysis analysis={analysis()} />)

    expect(within(panel()).getByText(/Generated by an LLM/)).toBeTruthy()
    expect(within(panel()).getByText(/Model: test\/model:free/)).toBeTruthy()
    expect(screen.getByText('A container in this namespace keeps restarting.')).toBeTruthy()
    expect(screen.getByText('The container process exits soon after it starts.')).toBeTruthy()
    expect(screen.getByText('Shown directly by the cited evidence')).toBeTruthy()
    expect(screen.getByText('The container is waiting to be restarted after repeated exits.')).toBeTruthy()
    expect(screen.getByText('Run a new investigation after the fix.')).toBeTruthy()
    expect(screen.getByText('The configuration may be missing.')).toBeTruthy()
  })

  it('marks a hypothesis as one that may be wrong', () => {
    const data = analysis()
    data.content.root_cause.kind = 'hypothesis'
    render(<AiAnalysis analysis={data} />)

    expect(screen.getByText('Hypothesis: an inference that may be wrong')).toBeTruthy()
    expect(screen.queryByText('Shown directly by the cited evidence')).toBeNull()
  })

  it('shows evidence references and every supporting observation', () => {
    render(<AiAnalysis analysis={analysis()} />)

    expect(screen.getAllByText(EVIDENCE_ID).length).toBeGreaterThanOrEqual(3)
    expect(screen.getByText(/The container is not ready and has restarted/)).toBeTruthy()
  })

  it('shows low confidence, and says when the application lowered it', () => {
    const data = analysis({ confidence_limited: true, model_confidence: 'high' })
    data.content.confidence = 'low'
    render(<AiAnalysis analysis={data} />)

    expect(screen.getByText('Low: the evidence is limited or ambiguous.')).toBeTruthy()
    expect(screen.getByText(/Lowered from high by the application/)).toBeTruthy()
  })

  it('does not mention a reduction when there was none', () => {
    render(<AiAnalysis analysis={analysis()} />)

    expect(screen.queryByText(/Lowered from/)).toBeNull()
  })

  it('shows remediation with its risk, and commands only as text', () => {
    render(<AiAnalysis analysis={analysis()} />)

    expect(screen.getByText('Risk: low')).toBeTruthy()
    expect(screen.getByText('Risk: high')).toBeTruthy()
    expect(screen.getByText(/advice only/)).toBeTruthy()
    const command = screen.getByText('kubectl logs pod/web -n demo --previous')
    expect(command.tagName).toBe('PRE')
    // Nothing in the panel can run anything.
    expect(within(panel()).queryAllByRole('button')).toHaveLength(0)
    expect(within(panel()).queryAllByRole('link')).toHaveLength(0)
  })

  it('shows the fallback when the analysis is unavailable', () => {
    render(<AiAnalysis analysis={analysis({ status: 'unavailable', reason: 'rate_limited', message: 'The rate limit was reached.', content: null })} />)

    expect(screen.getByText('Not available.')).toBeTruthy()
    expect(screen.getByText(/The rate limit was reached/)).toBeTruthy()
    expect(screen.getByText(/deterministic diagnosis above is complete without it/)).toBeTruthy()
  })

  it('shows when AI is disabled, as an unavailable analysis', () => {
    render(<AiAnalysis analysis={analysis({ status: 'unavailable', reason: 'disabled', message: 'The LLM is disabled.', content: null })} />)

    expect(screen.getByText(/The LLM is disabled/)).toBeTruthy()
    expect(screen.queryByText(/Generated by an LLM/)).toBeNull()
  })

  it('explains when no analysis was needed', () => {
    render(<AiAnalysis analysis={analysis({ status: 'not_needed', content: null })} />)

    expect(screen.getByText(/Not needed: the rules found no problems/)).toBeTruthy()
  })

  it('never shows generated content without a validated answer', () => {
    render(<AiAnalysis analysis={analysis({ status: 'generated', content: null, message: 'Missing.' })} />)

    expect(screen.queryByText(/Generated by an LLM/)).toBeNull()
    expect(screen.getByText('Not available.')).toBeTruthy()
  })

  it('renders nothing for reports without an analysis', () => {
    const { container } = render(<AiAnalysis analysis={null} />)

    expect(container.innerHTML).toBe('')
  })

  it('says when evidence was left out', () => {
    render(<AiAnalysis analysis={analysis({ evidence_omitted: 3 })} />)

    expect(screen.getByText(/3 evidence records were not sent/)).toBeTruthy()
  })
})
