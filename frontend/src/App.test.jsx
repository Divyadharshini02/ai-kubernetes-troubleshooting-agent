import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import App from './App.jsx'
import { analysis, chatAnswer, fakeFetch, investigation, message } from './test/fixtures.js'

let fake

function routes(detail) {
  return {
    'GET /api/health': () => [200, { status: 'ok', service: 'ai-kubernetes-troubleshooting-agent', version: '0.1.0' }],
    'GET /api/cluster/health': () => [503, { detail: { code: 'kubeconfig_unavailable', message: 'No kubeconfig.' } }],
    'GET /api/investigations': () => [200, [{ ...detail, events: undefined, report: undefined }]],
    'GET /api/investigations/inv-1': () => [200, detail],
    'GET /api/investigations/inv-1/chat': () => [200, []],
    'POST /api/investigations/inv-1/chat': () => [
      200,
      { question: message(1, 'user', 'question', 'Why?'), reply: message(2, 'assistant', 'answer', 'Because it exits.', { answer: chatAnswer() }) },
    ],
  }
}

async function openSaved(detail) {
  fake = fakeFetch(routes(detail))
  vi.stubGlobal('fetch', fake.fetch)
  render(<App />)
  fireEvent.click(await screen.findByRole('button', { name: /demo/ }))
  await screen.findByText('Diagnosis report: demo')
}

beforeEach(() => vi.unstubAllGlobals())
afterEach(cleanup)

describe('App with an investigation open', () => {
  it('shows the deterministic diagnosis, the AI analysis and the chat, in that order', async () => {
    await openSaved(investigation())

    const headings = screen.getAllByRole('heading', { level: 2 }).map((heading) => heading.textContent)
    const order = ['Diagnosis report: demo', 'AI root cause analysis', 'Ask about this investigation']
    expect(order.map((title) => headings.indexOf(title))).toEqual([...order.map((title) => headings.indexOf(title))].sort((a, b) => a - b))
    expect(screen.getByText('Container app is restarting repeatedly')).toBeTruthy()
    expect(within(screen.getByRole('region', { name: 'AI root cause analysis' })).getByText(/Generated by an LLM/)).toBeTruthy()
  })

  it('reads the AI status from the new analysis in the report facts', async () => {
    await openSaved(investigation())

    expect(screen.getByText('generated')).toBeTruthy()
  })

  it('still shows a report saved before the AI analysis existed', async () => {
    const old = investigation()
    old.report.ai_analysis = null
    old.report.llm = null
    old.explain_requested = false
    await openSaved(old)

    expect(screen.queryByRole('region', { name: 'AI root cause analysis' })).toBeNull()
    expect(screen.getByText('Not requested')).toBeTruthy()
    expect(screen.getByRole('region', { name: 'Ask about this investigation' })).toBeTruthy()
  })

  it('works with AI disabled', async () => {
    const disabled = investigation()
    disabled.report.ai_analysis = analysis({ status: 'unavailable', reason: 'disabled', message: 'The LLM is disabled.', content: null })
    await openSaved(disabled)

    expect(screen.getByText(/The LLM is disabled/, { selector: '.ai-panel p' })).toBeTruthy()
    expect(screen.getByText('Container app is restarting repeatedly')).toBeTruthy()
  })

  it('chatting never starts an investigation or contacts the cluster again', async () => {
    await openSaved(investigation())
    await screen.findByText(/No messages yet/)
    const before = fake.calls.length

    fireEvent.change(screen.getByLabelText('Your question'), { target: { value: 'Why?' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Because it exits.')

    const during = fake.calls.slice(before)
    expect(during.map((call) => `${call.method} ${call.path}`)).toEqual(['POST /api/investigations/inv-1/chat'])
    expect(fake.calls.some((call) => call.method === 'POST' && call.path === '/api/investigations')).toBe(false)
    expect(fake.calls.some((call) => /\/evidence|\/diagnosis/.test(call.path))).toBe(false)
  })

  it('shows no chat for an investigation that is still running', async () => {
    const running = investigation({ status: 'running', report: null })
    fake = fakeFetch({ ...routes(running), 'GET /api/investigations/inv-1/events': () => [200, {}] })
    vi.stubGlobal('fetch', fake.fetch)
    vi.stubGlobal(
      'EventSource',
      class {
        static CLOSED = 2
        addEventListener() {}
        close() {}
      },
    )
    render(<App />)
    fireEvent.click(await screen.findByRole('button', { name: /demo/ }))
    await screen.findByText(/Created\./)

    expect(screen.queryByRole('region', { name: 'Ask about this investigation' })).toBeNull()
  })
})
